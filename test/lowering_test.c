static reference_fn reference_for(const char *mnemonic)
{
	size_t i;

	for (i = 0; i < sizeof references / sizeof references[0]; i++)
		if (strcmp(references[i].mnemonic, mnemonic) == 0)
			return references[i].reference;
	return NULL;
}

/* -- the inputs -------------------------------------------------------- */

/* Lane values chosen so that operand order is visible. The NaNs carry
 * different payloads on purpose: x86 picks which source NaN survives by
 * operand order, so a lowering that swapped its operands would agree on
 * every ordinary value and disagree here. */
static const uint32_t PATTERNS[][4] = {
	{ 0x3F800000, 0x40000000, 0x40400000, 0x40800000 },	/* 1 2 3 4 */
	{ 0xBF800000, 0x3FC00000, 0x00000000, 0x80000000 },	/* -1 1.5 +0 -0 */
	{ 0x7F800000, 0xFF800000, 0x00000001, 0x807FFFFF },	/* inf denormal */
	/* THREE CONSECUTIVE all-NaN sets, and the count is what matters.
	 * Register r receives PATTERNS[(p + r) % count], so the two sources of
	 * a case are always a fixed distance apart in this table -- one apart
	 * for two of the operand shapes and two apart for the third. A single
	 * NaN row therefore never puts a NaN in both sources at once, and the
	 * both-NaN case is exactly where operand order becomes observable:
	 * with one NaN either order returns it, and only with two does the
	 * choice of which survives show. Measured, not assumed -- with one row
	 * an operand swap was detectable in vaddps and invisible in vmulps,
	 * vpand, vpor, vpxor, vpaddd, vandps and vxorps. */
	{ 0x7FC00001, 0x7FC00002, 0xFFC00003, 0x7F800001 },
	{ 0xFFC00009, 0x7F80000A, 0x7FC0000B, 0xFFC0000C },
	{ 0x7F800002, 0xFFC00005, 0x7FC00006, 0xFF800007 },
	{ 0x12345678, 0x9ABCDEF0, 0x00000000, 0xFFFFFFFF },	/* bit patterns */
	{ 0xFFFFFFFF, 0x7FFFFFFF, 0x80000000, 0x00000001 },	/* int edges */
};
#define PATTERN_COUNT (sizeof PATTERNS / sizeof PATTERNS[0])

int main(void)
{
	__m128i in[16], out[16];
	unsigned failures = 0, checked = 0, missing = 0, tolerated = 0;
	size_t c;

	for (c = 0; c < LOWERING_CASES; c++) {
		const struct lowering_case *entry = &lowering_table[c];
		reference_fn reference = NULL;
		reference3_fn reference3 = NULL;
		size_t p;

		if (entry->source3 < 0)
			reference = reference_for(entry->mnemonic);
		else
			reference3 = reference3_for(entry->mnemonic);

		if (!reference && !reference3) {
			/* Never a skip: a mnemonic added to the generator with no
			 * reference here would otherwise quietly stop being tested. */
			fprintf(stderr, "lowering: no reference for %s\n",
			        entry->mnemonic);
			missing++;
			continue;
		}

		for (p = 0; p < PATTERN_COUNT; p++) {
			__m128i expected;
			int r;

			/* A different pattern in every register, so that reading the
			 * wrong one cannot go unnoticed. */
			for (r = 0; r < 16; r++)
				in[r] = _mm_loadu_si128((const __m128i *)
				                        PATTERNS[(p + r) % PATTERN_COUNT]);
			memset(out, 0, sizeof out);
			entry->run(in, out);

			if (reference3)
				expected = reference3(in[entry->source1],
				                      in[entry->source2],
				                      in[entry->source3]);
			else
				expected = reference(in[entry->source1],
				                     in[entry->source2]);
			checked++;

			for (r = 0; r < 16; r++) {
				const __m128i *want = &in[r];

				if (r == LOWERING_SCRATCH)
					continue;	/* it may be destroyed */
				if (r == entry->destination)
					want = &expected;
				if (memcmp(&out[r], want, 16) == 0)
					continue;
				if (entry->nan_lane && r == entry->destination
				    && nan_equivalent(&out[r], want, entry->nan_lane)) {
					tolerated++;
					continue;
				}
				failures++;
				if (failures <= 8) {
					const uint32_t *got = (const uint32_t *)&out[r];
					const uint32_t *wanted = (const uint32_t *)want;

					fprintf(stderr,
					        "lowering: %s %s pattern %zu: xmm%d is "
					        "%08x%08x%08x%08x, want %08x%08x%08x%08x\n",
					        entry->mnemonic, entry->shape, p, r,
					        got[3], got[2], got[1], got[0],
					        wanted[3], wanted[2], wanted[1], wanted[0]);
				}
			}
		}
	}

	if (missing) {
		fprintf(stderr, "lowering: %u mnemonic(s) generated with no "
		        "reference -- add one rather than removing the case\n",
		        missing);
		return 1;
	}
	if (failures) {
		fprintf(stderr, "lowering: %u register comparison(s) wrong\n",
		        failures);
		return 1;
	}
	printf("lowering: %u lowerings executed over %d cases, every register "
	       "as the compiler computed it\n", checked, LOWERING_CASES);
	if (tolerated)
		printf("lowering: %u NaN payload difference(s) in Class F, not "
		       "counted -- both sides are NaN and the order is GCC's\n",
		       tolerated);
	return 0;
}
