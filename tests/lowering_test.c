/* Execute every lowering and check what it computed.
 *
 * The rest of the suite proves lowerings assemble and carry no VEX. That is
 * a property of their shape, and the src2-aliasing bug of Finding 25 had it
 * while computing a constant zero. This runs them.
 *
 * The reference is GCC compiling the equivalent SSE intrinsic. It cannot be
 * the AVX instruction itself: this is a Westmere, it has no AVX, and that is
 * the entire reason the project exists -- **the machine can execute the
 * output but not the input.** Using the compiler instead is not a weaker
 * oracle for being second-best, it is a genuinely independent one: a
 * different encoder, a different register allocator, and no knowledge of
 * what this project believes the answer to be.
 *
 * Three things are checked per case, and the last two are the ones that
 * catch the bugs this project has actually had:
 *
 *   * the destination holds what the intrinsic computed, bit for bit;
 *   * every other register is unchanged, except the scratch -- a lowering
 *     that gets the arithmetic right and clobbers a bystander is still
 *     wrong, and comparing only the destination would miss it;
 *   * the inputs include NaNs, infinities, zeros of both signs and
 *     denormals, because operand order is observable through NaN
 *     propagation even where the arithmetic commutes. That is what made
 *     swapping the operands the wrong fix for the aliasing case, and what
 *     291 vectors in src/fmaddsub.c already demonstrated once.
 *
 * A generated case with no reference here is a failure, never a skip. The
 * vacuous pass this avoids is the one where the mnemonic list grows and the
 * test silently stops covering the new entries.
 *
 * Termination: a fixed number of cases times a fixed number of input sets.
 * Nothing is spawned and nothing is written.
 */

#include <smmintrin.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>

struct lowering_case {
	const char *mnemonic;
	const char *shape;
	int source1;
	int source2;
	int length;
	void (*run)(const void *in, void *out);
};

#include "lowering_cases.inc"

/* -- the references, one per mnemonic ---------------------------------- */

typedef __m128i (*reference_fn)(__m128i src1, __m128i src2);

/* Written out rather than generated by a macro. A reference oracle is
 * the one place a reader must be able to see exactly what is being
 * compared against without expanding anything, and the style gate
 * treats a macro body as file-scope text, which is its own argument
 * against multi-line macros here.
 *
 * The casts are bit reinterpretations and cost nothing; every
 * reference takes and returns __m128i so one table can hold them all.
 */

static __m128i ref_addss(__m128i a, __m128i b)
{
	return _mm_castps_si128(_mm_add_ss(_mm_castsi128_ps(a),
	                            _mm_castsi128_ps(b)));
}

